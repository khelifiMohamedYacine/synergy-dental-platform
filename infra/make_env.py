"""Create a production .env with fresh random secrets for a given domain.

    py infra/make_env.py 203-0-113-10.sslip.io [admin@clinic.co.uk] > .env.production

The output contains secrets: keep it out of git (.env.* is ignored) and copy it to the
server as /opt/synergy/.env.
"""

import secrets
import sys


def token(n: int = 32) -> str:
    return secrets.token_urlsafe(n)


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    domain = sys.argv[1].strip().lower()
    admin_email = (sys.argv[2] if len(sys.argv) == 3 else "admin@example.test").strip().lower()
    pg = token(24)
    print(f"""# Production environment for https://{domain} (generated by infra/make_env.py)
SITE_DOMAIN={domain}

POSTGRES_DB=synergy
POSTGRES_USER=synergy
POSTGRES_PASSWORD={pg}

API_ENV=production
DATABASE_URL=postgresql+psycopg://synergy:{pg}@postgres:5432/synergy
JWT_SECRET={token(48)}
JWT_ACCESS_TTL_MINUTES=15
JWT_REFRESH_TTL_DAYS=7
CORS_ALLOWED_ORIGINS=
SERVICE_API_KEY={token(32)}
ENQUIRY_RATE_LIMIT=5/minute;30/day
SEED_ADMIN_EMAIL={admin_email}
SEED_ADMIN_NAME=Administrator
SEED_ADMIN_PASSWORD={token(12)}

WC_BASE_URL=http://wordpress
WC_CONSUMER_KEY=ck_{secrets.token_hex(20)}
WC_CONSUMER_SECRET=cs_{secrets.token_hex(20)}

WP_DB_NAME=wordpress
WP_DB_USER=wordpress
WP_DB_PASSWORD={token(24)}
WP_DB_ROOT_PASSWORD={token(24)}

WP_URL=https://{domain}
WP_ADMIN_USER=sd_site_owner
WP_ADMIN_PASSWORD={token(16)}
WP_ADMIN_EMAIL={admin_email}
SITE_NAME=Synergy Dental
SITE_PUBLIC=0
SYNERGY_API_URL=http://api:8000/api/v1""")


if __name__ == "__main__":
    main()
